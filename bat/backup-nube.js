#!/usr/bin/env node
/**
 * Respaldo lógico (.sql) de las bases de datos del proyecto, usando las MISMAS
 * librerías que ya instala el backend (mysql2 y pg). Así la VM no necesita
 * descargar pg_dump ni otro cliente de MySQL.
 *
 * Uso:   node bat/backup-nube.js <local|azure|supabase> <archivo_salida.sql>
 * Lee las credenciales de backend/.env
 */
const path = require('path');
const fs = require('fs');
const { createRequire } = require('module');

const BACKEND = path.resolve(__dirname, '..', 'backend');
const requireBackend = createRequire(path.join(BACKEND, 'package.json'));
requireBackend('dotenv').config({ path: path.join(BACKEND, '.env'), quiet: true });

const [, , destino, salida] = process.argv;
if (!['local', 'azure', 'supabase'].includes(destino) || !salida) {
  console.error('Uso: node bat/backup-nube.js <local|azure|supabase> <archivo_salida.sql>');
  process.exit(2);
}

const ahora = () => new Date().toString();

// ---------------- MySQL / MariaDB (XAMPP y Azure) ----------------
async function respaldarMySQL(cfg, out) {
  const mysql = requireBackend('mysql2/promise');
  const conn = await mysql.createConnection({ ...cfg, dateStrings: true, multipleStatements: false });
  const db = cfg.database;
  try {
    out.write(`-- Respaldo de \`${db}\` (${cfg.host}) generado ${ahora()}\n`);
    out.write('SET NAMES utf8mb4;\nSET FOREIGN_KEY_CHECKS=0;\n');
    out.write(`CREATE DATABASE IF NOT EXISTS \`${db}\`;\nUSE \`${db}\`;\n\n`);

    const [tablas] = await conn.query('SHOW FULL TABLES');
    const col = Object.keys(tablas[0] || {})[0];
    const base = tablas.filter(t => t.Table_type === 'BASE TABLE').map(t => t[col]);
    const vistas = tablas.filter(t => t.Table_type === 'VIEW').map(t => t[col]);

    for (const t of base) {
      const [[crear]] = await conn.query('SHOW CREATE TABLE ??', [t]);
      out.write(`-- Tabla ${t}\nDROP TABLE IF EXISTS \`${t}\`;\n${crear['Create Table']};\n`);
      const [filas] = await conn.query('SELECT * FROM ??', [t]);
      for (let i = 0; i < filas.length; i += 200) {
        const lote = filas.slice(i, i + 200).map(f => '(' + Object.values(f).map(v => conn.escape(v)).join(', ') + ')');
        const columnas = Object.keys(filas[0]).map(c => `\`${c}\``).join(', ');
        out.write(`INSERT INTO \`${t}\` (${columnas}) VALUES\n${lote.join(',\n')};\n`);
      }
      out.write(`-- ${filas.length} filas\n\n`);
    }
    for (const v of vistas) {
      const [[crear]] = await conn.query('SHOW CREATE VIEW ??', [v]);
      out.write(`DROP VIEW IF EXISTS \`${v}\`;\n${crear['Create View']};\n\n`);
    }
    out.write('SET FOREIGN_KEY_CHECKS=1;\n');
    return base.length;
  } finally {
    await conn.end();
  }
}

// ---------------- PostgreSQL (Supabase, esquema public) ----------------
const lit = v => (v === null ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const id = s => `"${s.replace(/"/g, '""')}"`;

async function respaldarPostgres(connectionString, out) {
  const { Client } = requireBackend('pg');
  const client = new Client({ connectionString, ssl: { rejectUnauthorized: false } });
  await client.connect();
  // Todos los valores llegan como texto tal cual los entrega PostgreSQL
  const crudo = { getTypeParser: () => v => v };
  try {
    out.write(`-- Respaldo esquema public de Supabase generado ${ahora()}\nBEGIN;\n\n`);
    const { rows: tablas } = await client.query(
      `SELECT c.oid, c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
       WHERE n.nspname = 'public' AND c.relkind IN ('r','p') ORDER BY c.relname`);

    const llavesForaneas = [];
    const ajustesSecuencia = [];

    for (const { oid, relname } of tablas) {
      const tabla = `public.${id(relname)}`;
      const { rows: cols } = await client.query(
        `SELECT a.attname, format_type(a.atttypid, a.atttypmod) AS tipo, a.attnotnull,
                a.attidentity, pg_get_expr(d.adbin, d.adrelid) AS defecto
         FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
         WHERE a.attrelid = $1 AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum`, [oid]);
      const { rows: cons } = await client.query(
        `SELECT conname, contype, pg_get_constraintdef(oid) AS def FROM pg_constraint
         WHERE conrelid = $1 AND contype IN ('p','u','c','f') ORDER BY contype DESC, conname`, [oid]);

      const lineas = [];
      const secuencias = [];
      let siempreIdentidad = false;
      for (const c of cols) {
        let l = `  ${id(c.attname)} ${c.tipo}`;
        if (c.attidentity === 'a') { l += ' GENERATED ALWAYS AS IDENTITY'; siempreIdentidad = true; }
        else if (c.attidentity === 'd') l += ' GENERATED BY DEFAULT AS IDENTITY';
        else if (c.defecto) {
          const seq = /^nextval\('([^']+)'::regclass\)$/.exec(c.defecto);
          if (seq) secuencias.push(`CREATE SEQUENCE IF NOT EXISTS ${seq[1]};\n`);
          l += ` DEFAULT ${c.defecto}`;
        }
        if (c.attnotnull) l += ' NOT NULL';
        lineas.push(l);
        if (c.attidentity || (c.defecto || '').startsWith('nextval(')) {
          ajustesSecuencia.push(`SELECT setval(pg_get_serial_sequence('${tabla}', '${c.attname}'), COALESCE(MAX(${id(c.attname)}), 0) + 1, false) FROM ${tabla};`);
        }
      }
      for (const k of cons) {
        if (k.contype === 'f') llavesForaneas.push(`ALTER TABLE ${tabla} ADD CONSTRAINT ${id(k.conname)} ${k.def};`);
        else lineas.push(`  CONSTRAINT ${id(k.conname)} ${k.def}`);
      }
      out.write(`-- Tabla ${relname}\nDROP TABLE IF EXISTS ${tabla} CASCADE;\n${secuencias.join('')}CREATE TABLE ${tabla} (\n${lineas.join(',\n')}\n);\n`);

      const nombres = cols.map(c => id(c.attname)).join(', ');
      const { rows: filas } = await client.query({ text: `SELECT * FROM ${tabla}`, types: crudo, rowMode: 'array' });
      for (let i = 0; i < filas.length; i += 200) {
        const lote = filas.slice(i, i + 200).map(f => '(' + f.map(lit).join(', ') + ')');
        out.write(`INSERT INTO ${tabla} (${nombres})${siempreIdentidad ? ' OVERRIDING SYSTEM VALUE' : ''} VALUES\n${lote.join(',\n')};\n`);
      }
      out.write(`-- ${filas.length} filas\n\n`);
    }
    if (llavesForaneas.length) out.write(llavesForaneas.join('\n') + '\n');
    if (ajustesSecuencia.length) out.write(ajustesSecuencia.join('\n') + '\n');
    out.write('\nCOMMIT;\n');
    return tablas.length;
  } finally {
    await client.end();
  }
}

// ---------------- Principal ----------------
(async () => {
  const e = process.env;
  const tmp = `${salida}.parcial`;
  const out = fs.createWriteStream(tmp);
  try {
    let n;
    if (destino === 'local') {
      n = await respaldarMySQL({ host: e.DB_LOCAL_HOST, port: Number(e.DB_LOCAL_PORT || 3306), user: e.DB_LOCAL_USER,
        password: e.DB_LOCAL_PASSWORD, database: e.DB_LOCAL_NAME }, out);
    } else if (destino === 'azure') {
      n = await respaldarMySQL({ host: e.DB_AZURE_HOST, port: 3306, user: e.DB_AZURE_USER,
        password: e.DB_AZURE_PASSWORD, database: e.DB_AZURE_NAME, ssl: { rejectUnauthorized: true } }, out);
    } else {
      n = await respaldarPostgres(e.SUPABASE_DB_URL, out);
    }
    await new Promise((ok, mal) => out.end(err => (err ? mal(err) : ok())));
    fs.renameSync(tmp, salida); // solo queda el archivo final si todo salió bien
    console.log(`OK ${destino}: ${n} tablas -> ${salida}`);
  } catch (err) {
    out.destroy();
    fs.rmSync(tmp, { force: true });
    console.error(`ERROR ${destino}: ${err.message}`);
    process.exit(1);
  }
})();